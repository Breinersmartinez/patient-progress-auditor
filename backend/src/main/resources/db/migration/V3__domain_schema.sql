-- Esquema del dominio del Momento 2 (docs/DICCIONARIO_DATOS_M2.md).
-- Ninguna clave foranea del dominio usa ON DELETE CASCADE: nada se borra (RNF-10).

-- Usuarios de demostracion (D23, D26): sin credenciales en el Momento 2.
ALTER TABLE app_users ALTER COLUMN password_hash DROP NOT NULL;
ALTER TABLE app_users ADD COLUMN display_name VARCHAR(100);
UPDATE app_users SET display_name = email WHERE display_name IS NULL;
ALTER TABLE app_users ALTER COLUMN display_name SET NOT NULL;
ALTER TABLE app_users ADD COLUMN is_demo BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE patients (
    id UUID PRIMARY KEY,
    alias VARCHAR(100) NOT NULL,
    bed VARCHAR(10),
    age SMALLINT,
    admitted_on DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE entries (
    id UUID PRIMARY KEY,
    patient_id UUID NOT NULL REFERENCES patients (id),
    entry_date DATE NOT NULL,
    body TEXT NOT NULL,
    author_id UUID NOT NULL REFERENCES app_users (id),
    source VARCHAR(10) NOT NULL DEFAULT 'TEXTO',
    structuring_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT entries_source_check CHECK (source IN ('TEXTO', 'VOZ')),
    CONSTRAINT entries_structuring_status_check CHECK (structuring_status IN ('ESTRUCTURADA', 'SIN_ESTRUCTURAR'))
);

CREATE INDEX idx_entries_patient_date ON entries (patient_id, entry_date, created_at);

CREATE TABLE entry_events (
    id UUID PRIMARY KEY,
    entry_id UUID NOT NULL REFERENCES entries (id),
    event_type VARCHAR(30) NOT NULL,
    symptom VARCHAR(20) NOT NULL,
    intensity VARCHAR(15) NOT NULL DEFAULT 'SIN_INDICAR',
    occurrences SMALLINT,
    origin VARCHAR(10) NOT NULL,
    confirmed_by UUID NOT NULL REFERENCES app_users (id),
    confirmed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT entry_events_type_check CHECK (event_type = 'SINTOMA'),
    CONSTRAINT entry_events_symptom_check CHECK (symptom IN (
        'VOMITO', 'DIARREA', 'NAUSEAS', 'FIEBRE', 'MAREO',
        'DOLOR_CABEZA', 'DOLOR_HUESO', 'APETITO_BAJO', 'ANIMO_DECAIDO')),
    CONSTRAINT entry_events_intensity_check CHECK (intensity IN ('LEVE', 'MODERADO', 'INTENSO', 'SIN_INDICAR')),
    CONSTRAINT entry_events_occurrences_check CHECK (occurrences IS NULL OR occurrences > 0),
    CONSTRAINT entry_events_origin_check CHECK (origin IN ('IA', 'EDITADO', 'MANUAL')),
    CONSTRAINT entry_events_entry_symptom_key UNIQUE (entry_id, symptom)
);

CREATE INDEX idx_entry_events_entry ON entry_events (entry_id);
CREATE INDEX idx_entry_events_symptom ON entry_events (symptom);

CREATE TABLE entry_versions (
    id UUID PRIMARY KEY,
    entry_id UUID NOT NULL REFERENCES entries (id),
    version_no INTEGER NOT NULL,
    body TEXT NOT NULL,
    origin VARCHAR(15) NOT NULL,
    created_by UUID NOT NULL REFERENCES app_users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT entry_versions_origin_check CHECK (origin IN ('IA_ACEPTADA', 'IA_EDITADA', 'MANUAL')),
    CONSTRAINT entry_versions_entry_version_key UNIQUE (entry_id, version_no)
);

CREATE TABLE agent_runs (
    id UUID PRIMARY KEY,
    run_type VARCHAR(20) NOT NULL,
    patient_id UUID NOT NULL REFERENCES patients (id),
    requested_by UUID NOT NULL REFERENCES app_users (id),
    period_start DATE,
    period_end DATE,
    status VARCHAR(15) NOT NULL DEFAULT 'EN_COLA',
    stop_reason VARCHAR(30),
    provider VARCHAR(50),
    model VARCHAR(100),
    fallback_used BOOLEAN NOT NULL DEFAULT FALSE,
    iterations INTEGER NOT NULL DEFAULT 0,
    tokens_in INTEGER NOT NULL DEFAULT 0,
    tokens_out INTEGER NOT NULL DEFAULT 0,
    cost_usd NUMERIC(10, 6),
    error_message VARCHAR(500),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT agent_runs_type_check CHECK (run_type IN ('INFORME', 'ESTRUCTURACION')),
    CONSTRAINT agent_runs_status_check CHECK (status IN ('EN_COLA', 'EN_CURSO', 'COMPLETADA', 'INCOMPLETA', 'FALLIDA')),
    CONSTRAINT agent_runs_stop_reason_check CHECK (stop_reason IS NULL OR stop_reason IN (
        'EXITO', 'MAX_ITERACIONES', 'MAX_TOKENS', 'TIMEOUT_HERRAMIENTA',
        'SALIDA_INVALIDA', 'PROVEEDOR_NO_DISPONIBLE'))
);

CREATE INDEX idx_agent_runs_patient ON agent_runs (patient_id, created_at DESC);
CREATE INDEX idx_agent_runs_status ON agent_runs (status);

CREATE TABLE agent_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES agent_runs (id),
    seq INTEGER NOT NULL,
    step_type VARCHAR(20) NOT NULL,
    tool_name VARCHAR(60),
    message VARCHAR(300),
    params JSONB,
    result JSONB,
    is_error BOOLEAN NOT NULL DEFAULT FALSE,
    duration_ms INTEGER,
    tokens_in INTEGER,
    tokens_out INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT agent_steps_type_check CHECK (step_type IN (
        'ESTADO', 'LLAMADA_LLM', 'HERRAMIENTA', 'VALIDACION', 'LIMITE', 'FALLBACK', 'ERROR')),
    CONSTRAINT agent_steps_run_seq_key UNIQUE (run_id, seq)
);

CREATE TABLE reports (
    id UUID PRIMARY KEY,
    patient_id UUID NOT NULL REFERENCES patients (id),
    report_type VARCHAR(10) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE_REVISION',
    status_reason TEXT,
    requested_by UUID NOT NULL REFERENCES app_users (id),
    run_id UUID REFERENCES agent_runs (id),
    provider VARCHAR(50),
    model VARCHAR(100),
    reviewed_by UUID REFERENCES app_users (id),
    reviewed_at TIMESTAMPTZ,
    approved_version_no INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reports_type_check CHECK (report_type IN ('SEMANAL', 'MENSUAL')),
    CONSTRAINT reports_status_check CHECK (status IN ('PENDIENTE_REVISION', 'INCOMPLETO', 'APROBADO', 'RECHAZADO')),
    CONSTRAINT reports_period_start_monday_check CHECK (EXTRACT(ISODOW FROM period_start) = 1),
    CONSTRAINT reports_period_length_check CHECK (
        (report_type = 'SEMANAL' AND period_end = period_start + 6)
        OR (report_type = 'MENSUAL' AND period_end = period_start + 27)),
    CONSTRAINT reports_review_check CHECK (
        (status IN ('APROBADO', 'RECHAZADO')) = (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
    CONSTRAINT reports_approved_version_check CHECK (status <> 'APROBADO' OR approved_version_no IS NOT NULL),
    CONSTRAINT reports_status_reason_check CHECK (status NOT IN ('INCOMPLETO', 'RECHAZADO') OR status_reason IS NOT NULL)
);

-- A lo sumo un informe vigente por paciente y periodo; uno RECHAZADO o INCOMPLETO no bloquea pedir otro.
CREATE UNIQUE INDEX uq_reports_current_period
    ON reports (patient_id, report_type, period_start)
    WHERE status IN ('PENDIENTE_REVISION', 'APROBADO');
CREATE INDEX idx_reports_patient_period ON reports (patient_id, period_start DESC);
CREATE INDEX idx_reports_status ON reports (status);

CREATE TABLE report_versions (
    id UUID PRIMARY KEY,
    report_id UUID NOT NULL REFERENCES reports (id),
    version_no INTEGER NOT NULL,
    origin VARCHAR(12) NOT NULL,
    content JSONB,
    plain_text TEXT,
    edited_by UUID REFERENCES app_users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT report_versions_origin_check CHECK (origin IN ('MODELO', 'ENFERMERIA')),
    CONSTRAINT report_versions_body_check CHECK (content IS NOT NULL OR plain_text IS NOT NULL),
    CONSTRAINT report_versions_editor_check CHECK (origin <> 'ENFERMERIA' OR edited_by IS NOT NULL),
    CONSTRAINT report_versions_report_version_key UNIQUE (report_id, version_no)
);

CREATE TABLE report_citations (
    report_version_id UUID NOT NULL REFERENCES report_versions (id),
    claim_key VARCHAR(40) NOT NULL,
    entry_id UUID NOT NULL REFERENCES entries (id),
    PRIMARY KEY (report_version_id, claim_key, entry_id)
);

CREATE TABLE monthly_report_weeks (
    monthly_report_id UUID NOT NULL REFERENCES reports (id),
    week_no SMALLINT NOT NULL,
    weekly_report_id UUID NOT NULL REFERENCES reports (id),
    PRIMARY KEY (monthly_report_id, week_no),
    CONSTRAINT monthly_report_weeks_week_check CHECK (week_no BETWEEN 1 AND 4),
    CONSTRAINT monthly_report_weeks_weekly_key UNIQUE (monthly_report_id, weekly_report_id)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id UUID NOT NULL REFERENCES app_users (id),
    actor_role VARCHAR(20) NOT NULL,
    action VARCHAR(40) NOT NULL,
    entity_type VARCHAR(30) NOT NULL,
    entity_id UUID NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    before_state JSONB,
    after_state JSONB,
    CONSTRAINT audit_logs_action_check CHECK (action IN (
        'APROBAR_INFORME', 'RECHAZAR_INFORME', 'EDITAR_INFORME', 'EDITAR_ENTRADA', 'REGISTRAR_ENTRADA_MEDICO')),
    CONSTRAINT audit_logs_entity_type_check CHECK (entity_type IN ('ENTRY', 'REPORT'))
);

CREATE INDEX idx_audit_logs_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_logs_actor ON audit_logs (actor_id, occurred_at DESC);
